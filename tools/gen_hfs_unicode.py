#!/usr/bin/env python3
"""Generate src/fs/hfs_plus/unicode_tables.rs from xnu's vfs_utfconvdata.h.

HFS+ stores names in the decomposed form produced by the macOS kernel's
`utf8_decodestr(..., UTF_DECOMPOSED)` (bsd/vfs/vfs_utfconv.c). Its data
tables ("Unicode 3.2 decomposition code (derived from Core Foundation)")
live in bsd/vfs/vfs_utfconvdata.h, APSL 2.0:

    https://github.com/apple-oss-distributions/xnu/blob/main/bsd/vfs/vfs_utfconvdata.h

The tables are transcribed verbatim so fstool decomposes and orders names
exactly as the kernel does — including what the kernel leaves alone
(U+2000-U+2FFF, U+F900-U+FAFF, everything outside the BMP and every code
point unassigned in Unicode 3.2) and the Unicode 3.2 combining classes.

Usage:
    python3 tools/gen_hfs_unicode.py path/to/vfs_utfconvdata.h \
        [path/to/UnicodeData-3.2.0.txt] > src/fs/hfs_plus/unicode_tables.rs

With UnicodeData-3.2.0.txt (https://www.unicode.org/Public/3.2-Update/)
the script also cross-checks the kernel tables against Unicode 3.2 and
reports every difference on stderr. As of xnu-11215 the decomposable set
is exactly the 3.2 canonical decompositions minus Apple's excluded
ranges, while the combining-class table differs in 25 code points: it
also carries the classes of the marks Unicode 4.0 added (U+0350-U+0357,
U+035D-U+035F, U+0610-U+0615, U+0656-U+0658, U+0CBC, U+17DD,
U+1939-U+193B). The kernel's table is what macOS uses, so it is what
fstool uses.
"""

import re
import sys
import textwrap

WANTED = {
    "__CFUniCharDecompositionTable": "u16",
    "__CFUniCharMultipleDecompositionTable": "u16",
    "__CFUniCharDecomposableBitmap": "u8",
    "__CFUniCharCombiningBitmap": "u8",
    "__CFUniCharCombiningPropertyBitmap": "u8",
}

RUST_NAMES = {
    "__CFUniCharDecompositionTable": "DECOMPOSITION_TABLE",
    "__CFUniCharMultipleDecompositionTable": "MULTIPLE_DECOMPOSITION_TABLE",
    "__CFUniCharDecomposableBitmap": "DECOMPOSABLE_BITMAP",
    "__CFUniCharCombiningBitmap": "COMBINING_BITMAP",
    "__CFUniCharCombiningPropertyBitmap": "COMBINING_PROPERTY_BITMAP",
}

DOCS = {
    "__CFUniCharDecompositionTable":
        "`(code point, value)` pairs sorted by code point; `value` packs a "
        "recursion flag (bit 15), a length (bits 12-14) and either the "
        "single mapped code point or an index into "
        "[`MULTIPLE_DECOMPOSITION_TABLE`] (bits 0-11).",
    "__CFUniCharMultipleDecompositionTable":
        "Multi-code-point decomposition sequences, indexed from "
        "[`DECOMPOSITION_TABLE`].",
    "__CFUniCharDecomposableBitmap":
        "Two-level bitmap of the code points the kernel decomposes "
        "(`unicode_decomposeable`).",
    "__CFUniCharCombiningBitmap":
        "Two-level bitmap of the code points that extend a combining run "
        "(`unicode_combinable`; includes the Hangul jamo).",
    "__CFUniCharCombiningPropertyBitmap":
        "Two-level table of canonical combining classes "
        "(`get_combining_class`): Unicode 3.2, plus the marks Unicode 4.0 "
        "added.",
}


def parse_tables(text):
    out = {}
    pat = re.compile(r"static const u_int(8|16|32)_t\s+(\w+)\[\]\s*=\s*\{(.*?)\};", re.S)
    for m in pat.finditer(text):
        name = m.group(2)
        if name in WANTED:
            body = re.sub(r"/\*.*?\*/", "", m.group(3), flags=re.S)
            vals = [int(v, 0) for v in re.findall(r"0[xX][0-9a-fA-F]+|\d+", body)]
            out[name] = vals
    missing = set(WANTED) - set(out)
    if missing:
        sys.exit(f"missing tables: {sorted(missing)}")
    return out


def emit(tables):
    w = sys.stdout.write
    w("// @generated by tools/gen_hfs_unicode.py from xnu bsd/vfs/vfs_utfconvdata.h\n")
    w("// (Copyright (c) 2000-2005 Apple Computer, Inc.; Apple Public Source\n")
    w("// License 2.0). Do not edit by hand: re-run the generator.\n")
    w("//\n")
    w("// The Unicode 3.2 decomposition and combining-class data the macOS\n")
    w("// kernel uses to normalise HFS+ names (see `super::unicode`).\n\n")
    for n, (name, ty) in enumerate(WANTED.items()):
        if n:
            w("\n")
        vals = tables[name]
        rust = RUST_NAMES[name]
        for line in textwrap.wrap(DOCS[name], 76):
            w(f"/// {line}\n")
        w(f"pub(crate) static {rust}: [{ty}; {len(vals)}] = [\n")
        per = 12 if ty == "u16" else 16
        fmt = "0x{:04X}" if ty == "u16" else "0x{:02X}"
        for i in range(0, len(vals), per):
            w("    " + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",\n")
        w("];\n")


# --- optional cross-check against UnicodeData-3.2.0.txt -------------------

def bitmap_test(bitmap, c):
    value = bitmap[(c >> 8) & 0xFF]
    if value == 0xFF:
        return True
    if value:
        sub = bitmap[256 + (value - 1) * 32:]
        return bool(sub[(c & 0xFF) // 8] & (1 << (c % 8)))
    return False


def ccc_of(prop, c):
    value = prop[c >> 8]
    if value:
        return prop[value * 256 + (c % 256)]
    return 0


def excluded(c):
    return 0x2000 <= c <= 0x2FFF or 0xF900 <= c <= 0xFAFF


def cross_check(tables, path):
    canon = {}
    ccc = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.rstrip("\n").split(";")
            if len(fields) < 6:
                continue
            first = int(fields[0], 16)
            last = first
            if fields[1].endswith("First>"):
                continue  # ranges carry no decompositions / classes
            if int(fields[3]) != 0:
                ccc[first] = int(fields[3])
            d = fields[5]
            if d and not d.startswith("<"):
                canon[first] = d
            del last
    decomposable = tables["__CFUniCharDecomposableBitmap"]
    prop = tables["__CFUniCharCombiningPropertyBitmap"]
    problems = 0
    for c in range(0x10000):
        if 0xAC00 <= c <= 0xD7A3:
            continue  # Hangul: algorithmic, handled outside the tables
        want = c in canon and not excluded(c)
        have = bitmap_test(decomposable, c)
        if want != have:
            problems += 1
            sys.stderr.write(f"decomposable mismatch U+{c:04X}: 3.2={want} kernel={have}\n")
        if ccc.get(c, 0) != ccc_of(prop, c):
            problems += 1
            sys.stderr.write(
                f"ccc mismatch U+{c:04X}: 3.2={ccc.get(c, 0)} kernel={ccc_of(prop, c)}\n")
    sys.stderr.write(f"cross-check against {path}: {problems} difference(s)\n")


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    with open(sys.argv[1], encoding="utf-8") as f:
        tables = parse_tables(f.read())
    emit(tables)
    if len(sys.argv) == 3:
        cross_check(tables, sys.argv[2])


if __name__ == "__main__":
    main()
